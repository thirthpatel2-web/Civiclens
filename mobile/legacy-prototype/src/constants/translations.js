export const getCityName = (cityId, langCode = 'en') => {
  if (!cityId) return 'Bengaluru';
  const city = CITY_TRANSLATIONS[cityId.toLowerCase()];
  if (!city) return cityId.toUpperCase();
  const langCity = city[langCode] || city.en;
  return langCity ? langCity.name : city.en?.name || cityId;
};

