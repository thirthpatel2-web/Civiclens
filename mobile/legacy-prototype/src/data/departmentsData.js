// Helper function to detect department based on query keywords
export const detectDepartment = (queryText = '', cityId = 'bengaluru') => {
  const lower = queryText.toLowerCase();
  
  for (const dept of ALL_PUBLIC_AUTHORITIES) {
    if (dept.keywords && dept.keywords.some((kw) => lower.includes(kw))) {
      return dept;
    }
  }

  const cityDepts = DEPARTMENTS_BY_CITY[cityId] || DEPARTMENTS_BY_CITY['bengaluru'];
  return cityDepts[0] || ALL_PUBLIC_AUTHORITIES[0];
};

export const getDepartmentById = (deptId) => {
  return ALL_PUBLIC_AUTHORITIES.find(d => d.id === deptId) || ALL_PUBLIC_AUTHORITIES[0];
};

export const getDepartmentsByTier = (tier = 'all') => {
  if (tier === 'all') return ALL_PUBLIC_AUTHORITIES;
  return ALL_PUBLIC_AUTHORITIES.filter(d => d.tier === tier);
};
